<script>
import head from '@mixins/head'
import methods from '@mixins/methods'
import {
  stockpileList,
  petStockpileList,
  upStairsRate,
  downStairsRate,
  categoryA1,
  categoryA2,
  categoryB1,
  categoryB2,
  categoryB3,
  categoryC,
  categoryD1,
  categoryD2,
  lineShareIds
} from '@@/stockpile.config'
import { tipsTitles } from '@@/tips.config'
import ToolResultModal from '@partials/tool/ToolResultModal'
import TipsListItem from '@partials/tips/TipsListItem'

export default {
  name: 'PageToolResult',
  components: {
    ToolResultModal,
    TipsListItem
  },
  mixins: [head, methods],
  localStorage: {
    $toolValues: {
      type: Object
    }
  },
  beforeRouteEnter(to, from, next) {
    next((vm) => {
      const values = vm.getLatestToolValues(vm.$toolValues)
      if (!Array.isArray(values.family) || values.family.length === 0) {
        next({ name: 'tool' })
      }
    })
  },
  data() {
    return {
      initialVisibleCount: 3,
      showAllItems: false,
      isSettingsOpen: false,
      hasPet: false,
      stockpileList: [],
      categoryStockpileList: {},
      category: [],
      mailShareText: '',
        lineShareTextRaw: '',
      bodyAttrs: {
        class: 'PageToolResult'
      },
      meta: {
        title: this.$getTitle('toolResult', this.$i18n.locale),
        description: this.$i18n.t('meta.description')
      },
      isUpstairs: false
    }
  },
  computed: {
    visibleStockpileList() {
      return this.showAllItems
        ? this.stockpileList
        : this.stockpileList.slice(0, this.initialVisibleCount)
    },
    petStockpileList() {
      return petStockpileList
    },
    ctaTextLeft() {
      return this.$t('text26')
    },
    ctaTextRight() {
      return this.$t('text27')
    },
    ctaButtonText() {
      return this.$t('text28')
    },
    recommendTips() {
      const isUpstairs = !!this.isUpstairs
      const hasPet = !!this.hasPet
      const candidates = tipsTitles.filter(({ category }) => {
        if (category === 'apartment') {
          return isUpstairs
        }
        if (category === 'hasPet') {
          return hasPet
        }
        return true
      })
      const shuffle = (list) => {
        const items = [...list]
        for (let i = items.length - 1; i > 0; i -= 1) {
          const j = Math.floor(Math.random() * (i + 1))
          ;[items[i], items[j]] = [items[j], items[i]]
        }
        return items
      }
      const priorities = candidates.map((item) => Number(item.priority) || 0)
      const maxPriority = priorities.length ? Math.max(...priorities) : 0
      const highPriority = candidates.filter((item) => (Number(item.priority) || 0) === maxPriority)
      const rest = candidates.filter((item) => (Number(item.priority) || 0) !== maxPriority)

      return [...shuffle(highPriority), ...shuffle(rest)].slice(0, 6)
    },
    recommendTipsTitle() {
      return this.$t('text29')
    },
    recommendTipsMoreText() {
      return this.$t('text30')
    },
    settingsTitle() {
      return this.$t('text31')
    },
    settingsDateLabel() {
      return this.$t('text32')
    },
    settingsFamilyLabel() {
      return this.$t('text33')
    },
    settingsHomeLabel() {
      return this.$t('text34')
    },
    settingsPetLabel() {
      return this.$t('text35')
    },
    settingsDate() {
      const storedDate = this.$toolValues && this.$toolValues.date
      if (storedDate && typeof storedDate === 'string') {
        const [year, month, day] = storedDate.split('-')
        if (year && month && day) {
          return `${year}/${month}/${day}`
        }
      }

      const today = this.formatStorageDate(new Date())
      const [year, month, day] = today.split('-')
      return `${year}/${month}/${day}`
    },
    settingsFamily() {
      const values = this.getLatestToolValues(this.$toolValues)

      if (!Array.isArray(values.family)) {
        return []
      }

      const family = [...values.family].sort((a, b) => a.id - b.id)

      return family.map((person) => ({
        id: person.id,
        label: this.formatPersonLabel(person)
      }))
    },
    settingsHome() {
      return this.isUpstairs ? this.$t('text36') : this.$t('text37')
    },
    settingsPet() {
      return this.hasPet ? this.$t('text38') : this.$t('text39')
    },
    settingsEditText() {
      return this.$t('text40')
    }
  },
  mounted() {
    const toolValues = this.getLatestToolValues(this.$toolValues)
    const { isUpstairs = false, family = [], hasPet = false } = toolValues
    this.isUpstairs = isUpstairs
    const { length: familyLength } = family
    const stockpileRate = isUpstairs ? upStairsRate : downStairsRate
    const isHighRate = (() => stockpileRate === upStairsRate)()
    const isLowRate = (() => stockpileRate === downStairsRate)()
    const states = family.map(({ state }) => state)
    const includeAged = (() => {
      return states.some((state) => /aged/.test(state))
    })()
    const onlyInfants = (() => {
      return states.every((state) => /infants/.test(state))
    })()
    // 生理用品が必要な女性グループ
    const sanitaryItemsGroup = (() => {
      return states.some((state) => state === 'child2Female' || state === 'adultFemale')
    })()
    // 基礎化粧品が必要な女性グループ
    const skinCareGroup = states.filter((state) => /Female/.test(state) && !/^(infants|child1)/.test(state))
    const sumQuantity = (quantity, required) => {
      if (typeof required === 'object') {
        for (const state of states) {
          quantity += required[state]
        }
      }

      return quantity
    }
    const innerStockpileList = stockpileList
      .map((stockpile, index, self) => {
        const { id, required } = stockpile
        let quantity = 0

        if (categoryA1.includes(id)) {
          if (!onlyInfants) {
            quantity = sumQuantity(quantity, required)

            if (isHighRate) {
              quantity *= 2
            }
          }
        } else if (categoryA2.includes(id)) {
          if (!onlyInfants) {
            if (isLowRate) {
              if (familyLength <= 5) {
                quantity = 3
              } else {
                quantity = 6
              }
            } else if (isHighRate) {
              if (familyLength <= 5) {
                quantity = 7
              } else {
                quantity = 14
              }
            }
          }
        } else if (categoryB1.includes(id)) {
          if (familyLength <= 5) {
            quantity = 1
          } else {
            quantity = 2
          }
        } else if (categoryB2.includes(id)) {
          if (familyLength <= 3) {
            quantity = 1
          } else if (familyLength >= 4 && familyLength <= 6) {
            quantity = 2
          } else {
            quantity = 3
          }
        } else if (categoryB3.includes(id)) {
          if (familyLength <= 5) {
            quantity = 2
          } else {
            quantity = 4
          }
        } else if (categoryC.includes(id)) {
          quantity = familyLength
        } else if (categoryD1.includes(id)) {
          if (includeAged) {
            quantity = ''
          }
        } else if (categoryD2.includes(id)) {
          if (!onlyInfants) {
            quantity = ''
          }
        } else if (id === 43) {
          if (sanitaryItemsGroup) {
            quantity = 30
          }
        } else if (id === 44) {
          quantity = skinCareGroup.length
        } else if (id === 59) {
          quantity = ''
        } else {
          // イレギュラーではない品目
          quantity = Math.ceil(sumQuantity(quantity, required) * stockpileRate)
        }

        return {
          ...stockpile,
          quantity
        }
      })
      .filter(({ quantity }) => quantity !== 0)
      .sort((a, b) => (a.id < b.id ? -1 : 1))

    this.category = Array.from(new Set(innerStockpileList.map((prop) => prop.group[this.$i18n.locale])))
    this.stockpileList = innerStockpileList
    this.stockpileList.forEach((prop) => {
      this.categoryStockpileList[prop.group[this.$i18n.locale]] =
        this.categoryStockpileList[prop.group[this.$i18n.locale]] || []
      this.categoryStockpileList[prop.group[this.$i18n.locale]].push(prop)
    })

    const createShareText = (callback) => {
      const encodeText = (value) => encodeURIComponent(value)
      let shareText = encodeText(callback())
      let message = ''
      let url = ''

      message = this.$t('text41')
      url =
        this.$i18n.locale === 'ja'
          ? 'https://www.bichiku.metro.tokyo.lg.jp/tool/'
          : 'https://www.bichiku.metro.tokyo.lg.jp/en/tool/'

      shareText += encodeText(`

========
${message}
${url}`)

      return shareText
    }

    const lineShareTextRaw = (() => {
      const message = this.$t('text41')
      const url =
        this.$i18n.locale === 'ja'
          ? 'https://www.bichiku.metro.tokyo.lg.jp/tool/'
          : 'https://www.bichiku.metro.tokyo.lg.jp/en/tool/'

      return `${message}\n${url}`
    })()

    const mailShareText = createShareText(() => {
      let shareText = ''

      shareText = `${this.$t('text43', { family: familyLength })}\n`

      for (const key of this.category) {
        shareText += `

${key}`
        for (const stockpile of this.categoryStockpileList[key]) {
          const { quantity, item, unit } = stockpile

          shareText += `
${item[this.$i18n.locale]} ${quantity}${unit[this.$i18n.locale]}`
        }
      }

      if (hasPet) {
        const key = this.$t('text05')
        shareText += `

${key}`
        for (const shareId of petStockpileList) {
          const { item } = shareId
          console.log(shareId)
          shareText += `
${item[this.$i18n.locale]}`
        }
      }

      return shareText
    })

    this.hasPet = hasPet
    this.mailShareText = mailShareText
    this.lineShareTextRaw = lineShareTextRaw
  },
  methods: {
    formatPersonLabel(person) {
      let text = ''

      const { sex, generation, id } = person

      if (this.$i18n.locale === 'ja') {
        text += `${id}\u4EBA\u76EE\uFF1A`

        switch (sex) {
          case 'male':
            text += '\u7537\u6027 '
            break
          case 'female':
            text += '\u5973\u6027 '
            break
          default:
            text += '\u6027\u5225 '
        }

        switch (generation) {
          case 'infants':
            text += '\u4E73\u5E7C\u5150 (0\u301C2\u6B73)'
            break
          case 'child1':
            text += '\u5E7C\u5150 (3\u6B73\u301C\u5C0F\u5B66\u751F)'
            break
          case 'child2':
            text += '\u4E2D\u5B66\u751F\u4EE5\u4E0A'
            break
          case 'adult':
            text += '\u6210\u4EBA (18\u6B73\u4EE5\u4E0A)'
            break
          case 'aged':
            text += '\u9AD8\u9F62\u8005 (65\u6B73\u4EE5\u4E0A)'
            break
          default:
            text += '\u5E74\u9F62\u672A\u5165\u529B'
        }
      } else {
        text += `${id}th: `

        switch (sex) {
          case 'male':
            text += 'Male '
            break
          case 'female':
            text += 'Female '
            break
          default:
            text += 'Gender '
        }

        switch (generation) {
          case 'infants':
            text += 'Babies/infants (0-2)'
            break
          case 'child1':
            text += 'Children (3 to 6th grade)'
            break
          case 'child2':
            text += 'Children (junior high or older)'
            break
          case 'adult':
            text += 'Adults (18 or older)'
            break
          case 'aged':
            text += 'Elderly (65 or older)'
            break
          default:
            text += 'Age not entered'
        }
      }

      return text
    },
    printResult() {
      window.print()
    },
    toggleDetail() {
      const scrollY = window.scrollY
      this.showAllItems = !this.showAllItems
      this.$nextTick(() => {
        window.scrollTo({ top: scrollY, behavior: 'auto' })
      })
    },
    jumpStockpile(index) {
      if (!this.showAllItems) {
        this.showAllItems = true
      }
      this.$nextTick(() => {
        const target = document.querySelector(`#stockpile${index}`)
        if (target) {
          target.scrollIntoView({ behavior: 'smooth' })
        }
      })
    },
    jumpPetStockpile(index) {
      if (!this.showAllItems) {
        this.showAllItems = true
      }
      this.$nextTick(() => {
        const target = document.querySelector(`#petStockpile${index}`)
        if (target) {
          target.scrollIntoView({ behavior: 'smooth' })
        }
      })
    }
  }
}
</script>










